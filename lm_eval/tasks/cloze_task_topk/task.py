def get_rank(word, results):
    word = word.lower()
    for i, result in enumerate(results):
        if word == result[0].lower():
            return i
    return None

def reciprocal_rank(rank):
    if rank is None:
        return 0
    return 1 / (rank + 1)

def top_k(rank, k=5):
    total = len(rank)
    count = 0
    for r in rank:
        if r is not None and r < k:
            count += 1
    return count / total

def count_rank(rank):
    count = 0
    for r in rank:
        if r is not None:
            count += 1
    return count



class WordCountLimiterLogitsProcessor(LogitsProcessor):
    def __init__(self, tokenizer, desired_word_count, input_text, model=None, device=None):
        self.tokenizer = tokenizer
        self.desired_word_count = desired_word_count
        self.prompt_length = tokenizer.encode(input_text, return_tensors="pt", add_special_tokens=False).shape[1]

        disallowed_ids = set()
        for token_id in tokenizer.get_vocab().values():
            token_text = tokenizer.decode([token_id])
            if token_text.startswith(" ") or not token_text.strip().isalpha():
                if token_text in tokenizer.special_tokens_map.values():
                    continue
                disallowed_ids.add(token_id)
        self.disallowed_ids = list(disallowed_ids)

    def __call__(self, input_ids, scores):
        probs = torch.softmax(scores, dim=-1)
        new_probs = probs.clone()
        for i, input in enumerate(input_ids):
            text = self.tokenizer.decode(input[self.prompt_length:], skip_special_tokens=True)
            word_count = len(text.split())
            print(f"total_text: {self.tokenizer.decode(input, skip_special_tokens=False)} text: {text}, word_count: {word_count}")
            if not word_count == self.desired_word_count:
                continue
            disallowed_mass = probs[i, self.disallowed_ids].sum()
            
            new_probs[i, self.disallowed_ids] = 0
            new_probs[i, self.tokenizer.eos_token_id] += disallowed_mass
            new_scores = torch.log(new_probs) + torch.log(torch.exp(scores).sum(dim=-1, keepdim=True))
            scores[i] = new_scores[i]
        return scores


class ClozeTaskTopK(ConfigurableTask):
    VERSION = 1
    DATASET_PATH = "Hplm/historical-cloze-max-filtered"
    DATASET_NAME = None
    MAX_LENGTH = 4
    WORDS_TO_GENERATE = 1
    BEAMS = 50
    TOPK_INTERVALS = [1, 5, 10, 20, 50]
    

    def __init__(self):
        super().__init__(config={"metadata": {"version": self.VERSION}})

    def has_training_docs(self):
        return False

    def has_validation_docs(self):
        return False

    def has_test_docs(self):
        return True
    
    def test_docs(self):
        #random.seed(42)
        return self.dataset["test"].select(random.sample(range(len(self.dataset["test"])), 2))
    
    def doc_to_text(self, doc):
        text = doc["text"]
        return " ".join(text.split(' ')[:-1])

    def should_decontaminate(self):
        return True

    def doc_to_decontamination_query(self, doc):
        return doc["context"]

    def doc_to_target(self, doc):
        text = doc["text"]
        return ' ' + text.split(' ')[-1]

    def construct_requests(self, doc, ctx, **kwargs):
        """Uses RequestFactory to construct Requests and returns an iterable of
        Requests which will be sent to the LM.

        :param doc:
            The document as returned from training_docs, validation_docs, or test_docs.
        :param ctx: str
            The context string, generated by fewshot_context. This includes the natural
            language description, as well as the few shot examples, and the question
            part of the document for `doc`.
        """
        word_limiter = partial(WordCountLimiterLogitsProcessor, desired_word_count=self.WORDS_TO_GENERATE, input_text=ctx)
        return [
            Instance(
                request_type="generate_until",
                doc=doc,
                arguments=(ctx,{"logits_processor": [word_limiter], "num_beams": self.BEAMS, "num_return_sequences": self.BEAMS, "output_scores": True, "output_logits": False, "return_dict_in_generate": True, "max_gen_toks": self.MAX_LENGTH, "length_penalty": 0}), #"logits_processor": [word_limiter], "output_logits": True,
                idx=0,
                **kwargs,
            ),
            Instance(
                request_type="loglikelihood",
                doc=doc,
                arguments=(ctx, self.doc_to_target(doc)),
                idx=0,
                **kwargs,
            )
        ]

    def process_results(self, doc, results):
        """Take a single document and the LM results and evaluates, returning a
        dict where keys are the names of submetrics and values are the values of
        the metric for that one document

        :param doc:
            The document as returned from training_docs, validation_docs, or test_docs.
        :param results:
            The results of the requests created in construct_requests.
        """

        reults_top_k = results[0]

        reults_perplexity = results[1]
        ll, is_greedy = reults_perplexity[0]
        
        word = self.doc_to_target(doc)
        rank = get_rank(word, reults_top_k)
        result = {
            "rank": rank,
            "perplexity": ll,
            "acc": int(is_greedy),
            "reciprocal_rank": reciprocal_rank(rank),
        }
        for interval in self.TOPK_INTERVALS:
            result[f"top_{interval}"] = 1 if rank is not None and rank < interval else 0
        return result

    def aggregation(self):
        """
        :returns: {str: [float] -> float}
            A dictionary where keys are the names of submetrics and values are
            functions that aggregate a list of metrics
        """
        result = {
            "rank" : count_rank,
            "perplexity": np.mean,#get_metric_aggregation("perplexity"),
            "acc": get_metric_aggregation("acc"),
            "reciprocal_rank": np.mean,
        }
        for interval in self.TOPK_INTERVALS:
            result[f"top_{interval}"] = np.mean
        return result

    def higher_is_better(self):
        """
        :returns: {str: bool}
            A dictionary where keys are the names of submetrics and values are
            whether a higher value of the submetric is better
        """
        return {
            "rank": True,
        }
